using System.Text.Json;
using YoutubeExplode.Common;
using YoutubeExplode.Videos.ClosedCaptions;
using YoutubeExplode.Videos.Streams;

namespace YoutubeExplode.Cli.Utils;

// Stream info types have multiple public constructors, so they can't be deserialized directly.
// This type mirrors the union of their properties and is converted to the concrete type afterwards.
internal record StreamInfoDto(
    string Url,
    ContainerDto Container,
    FileSizeDto Size,
    BitrateDto Bitrate,
    string? AudioCodec,
    LanguageDto? AudioLanguage,
    bool? IsAudioLanguageDefault,
    string? VideoCodec,
    VideoQualityDto? VideoQuality,
    ResolutionDto? VideoResolution,
    bool IsVideoUpscaled
)
{
    public IStreamInfo ToStreamInfo()
    {
        var container = Container.ToContainer();
        var size = Size.ToFileSize();
        var bitrate = Bitrate.ToBitrate();
        var audioLanguage = AudioLanguage?.ToLanguage();

        return (AudioCodec, VideoCodec, VideoQuality, VideoResolution) switch
        {
            ({ } a, { } v, { } q, { } r) => new MuxedStreamInfo(
                Url,
                container,
                size,
                bitrate,
                a,
                audioLanguage,
                IsAudioLanguageDefault,
                v,
                q.ToVideoQuality(),
                r.ToResolution(),
                IsVideoUpscaled
            ),
            ({ } a, null, _, _) => new AudioOnlyStreamInfo(
                Url,
                container,
                size,
                bitrate,
                a,
                audioLanguage,
                IsAudioLanguageDefault
            ),
            (null, { } v, { } q, { } r) => new VideoOnlyStreamInfo(
                Url,
                container,
                size,
                bitrate,
                v,
                q.ToVideoQuality(),
                r.ToResolution(),
                IsVideoUpscaled
            ),
            _ => throw new JsonException(
                "Stream info must contain an audio codec, a video codec with its quality and resolution, or both."
            ),
        };
    }
}

internal record ClosedCaptionTrackInfoDto(string Url, LanguageDto Language, bool IsAutoGenerated)
{
    public ClosedCaptionTrackInfo ToClosedCaptionTrackInfo() =>
        new(Url, Language.ToLanguage(), IsAutoGenerated);
}

internal record ContainerDto(string Name)
{
    public Container ToContainer() => new(Name);
}

internal record FileSizeDto(long Bytes)
{
    public FileSize ToFileSize() => new(Bytes);
}

internal record BitrateDto(long BitsPerSecond)
{
    public Bitrate ToBitrate() => new(BitsPerSecond);
}

internal record LanguageDto(string Code, string Name)
{
    public Language ToLanguage() => new(Code, Name);
}

internal record VideoQualityDto(string Label, int MaxHeight, int Framerate)
{
    public VideoQuality ToVideoQuality() => new(Label, MaxHeight, Framerate);
}

internal record ResolutionDto(int Width, int Height)
{
    public Resolution ToResolution() => new(Width, Height);
}
