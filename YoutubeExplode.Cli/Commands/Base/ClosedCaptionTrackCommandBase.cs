using System.Text.Json;
using System.Threading;
using System.Threading.Tasks;
using CliFx.Infrastructure;
using PowerKit.Json.Extensions;
using YoutubeExplode.Videos.ClosedCaptions;

namespace YoutubeExplode.Cli.Commands.Base;

// Commands that operate on a single closed caption track, identified by track info JSON from stdin
public abstract class ClosedCaptionTrackCommandBase : CommandBase
{
    protected static async ValueTask<ClosedCaptionTrackInfo> ReadClosedCaptionTrackInfoAsync(
        IConsole console,
        CancellationToken cancellationToken
    )
    {
        var json = await ReadJsonAsync(console, cancellationToken);

        var url =
            json.GetPropertyOrNull("url")?.GetStringOrNull()
            ?? throw new JsonException("Property 'url' is missing.");

        var language = json.GetPropertyOrNull("language") is { ValueKind: JsonValueKind.Object } l
            ? new Language(
                l.GetPropertyOrNull("code")?.GetStringOrNull()
                    ?? throw new JsonException("Property 'language.code' is missing."),
                l.GetPropertyOrNull("name")?.GetStringOrNull()
                    ?? throw new JsonException("Property 'language.name' is missing.")
            )
            : throw new JsonException("Property 'language' is missing.");

        var isAutoGenerated =
            json.GetPropertyOrNull("isAutoGenerated")?.GetBooleanOrNull() ?? false;

        return new ClosedCaptionTrackInfo(url, language, isAutoGenerated);
    }
}
